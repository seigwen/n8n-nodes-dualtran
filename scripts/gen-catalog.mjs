#!/usr/bin/env node
/**
 * gen-catalog.mjs — build catalog.json from the fixtures plus the core BUILTINS.
 *
 * The n8n node UI cannot fetch models.dev at runtime (see conformance.json →
 * platformLimits R2), so the provider/model catalogue is a STATIC snapshot that
 * this script regenerates at build time (npm run catalog). Inputs only: the
 * frozen scripts/catalog-sources/ fixtures and the vendored core (no network).
 *
 *   scripts/catalog-sources/models-dev-sample.json  provider + model snapshot
 *   scripts/catalog-sources/provider-aliases.json   alias -> canonical provider id
 *   scripts/catalog-sources/language-names.json     language catalogue for the target picker
 *   dualtran (vendor)             BUILT_IN_PROVIDERS: curated ids/labels/apis
 *
 * Output shape:
 *   { snapshot, languages:[{id,label}], languagesSource, providers:[
 *       { id, name, api, builtIn, models:[{ id, label, reasoning }] } ] }
 *
 * Rules encoded here (and re-checked by scripts/conformance/payload.mjs):
 *   - ONE alphabetical list by label (Intl.Collator en/numeric), `Custom…` last
 *   - alias twins deduped: an alias id that resolves to a canonical id is
 *     dropped (scripts/catalog-sources/provider-aliases.json)
 *   - `api` is the provider API base (chat endpoint suffix stripped)
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import * as core from 'dualtran';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const facts = (name) => JSON.parse(fs.readFileSync(path.join(ROOT, 'scripts', 'catalog-sources', name), 'utf8'));

const sample = facts('models-dev-sample.json');
const aliases = facts('provider-aliases.json');
const languageNames = facts('language-names.json');

const collator = new Intl.Collator('en', { numeric: true, sensitivity: 'base' });
const canonical = (id) => aliases[id] ?? id;

/** "https://api.deepseek.com/v1/chat/completions" -> "https://api.deepseek.com/v1" */
function apiBase(value) {
	if (typeof value !== 'string' || value.trim() === '') return '';
	return value
		.trim()
		.replace(/\/(chat\/completions|messages|completions)\/?$/i, '')
		.replace(/\/+$/, '');
}

function reasoningOf(model) {
	const declared = Array.isArray(model.reasoning_options) ? model.reasoning_options : [];
	const effort = declared.find((entry) => entry && entry.type === 'effort');
	return Array.isArray(effort?.values)
		? effort.values.filter((value) => typeof value === 'string' && value)
		: [];
}

/** Curated core providers, keyed by the id the node stores (alias-safe). */
const builtIns = new Map();
for (const provider of core.BUILT_IN_PROVIDERS ?? []) {
	builtIns.set(provider.id, provider);
}

const builtInIds = new Set(builtIns.keys());
const providers = [];

for (const [rawId, provider] of Object.entries(sample)) {
	if (aliases[rawId]) continue; // alias twin of another catalogue entry
	const id = canonical(rawId);
	// Alias twins are deduped on the canonical id: the canonical entry wins.
	if (providers.some((entry) => entry.id === id)) continue;
	const builtIn = builtIns.get(id);
	const name = (builtIn?.name ?? provider.name ?? id).trim();
	const api = apiBase(provider.api || builtIn?.apiBase || '');
	const models = Object.entries(provider.models ?? {})
		.map(([modelId, model]) => ({
			id: model.id || modelId,
			label: (model.name || model.id || modelId).trim(),
			reasoning: reasoningOf(model),
		}))
		.sort((a, b) => collator.compare(a.label, b.label) || collator.compare(a.id, b.id));
	providers.push({ id, name, api, builtIn: builtInIds.has(id), models });
}

providers.sort((a, b) => collator.compare(a.name, b.name) || collator.compare(a.id, b.id));

const languages = Object.entries(languageNames)
	.map(([id, label]) => ({ id, label: String(label).trim() }))
	.sort((a, b) => collator.compare(a.label, b.label));

const catalog = {
	snapshot: 'scripts/catalog-sources/models-dev-sample.json',
	generatedBy: 'scripts/gen-catalog.mjs',
	languagesSource: 'scripts/catalog-sources/language-names.json',
	languages,
	providers,
};

const target = path.join(ROOT, 'catalog.json');
fs.writeFileSync(target, `${JSON.stringify(catalog, null, '	')}\n`);

// The node imports the catalogue through a tiny CJS shim: JSON imports would
// need resolveJsonModule in the build path, and the generated file keeps the
// snapshot and the code in lockstep (same command, same run).
const shim = path.join(ROOT, 'catalog.generated.js');
const banner = [
	'// GENERATED by scripts/gen-catalog.mjs — do not edit by hand.',
	'// CommonJS on purpose: the node is bundled to CJS and imports this file.',
	"module.exports = require('./catalog.json');",
	'',
].join('\n');
fs.writeFileSync(shim, banner);

console.log(
	`[catalog] ${providers.length} providers (${providers.filter((p) => p.builtIn).length} built-in), ` +
		`${languages.length} languages -> catalog.json + catalog.generated.js`,
);
